"use client";
import Link from "next/link";
import { useCallback, useEffect, useState, type FormEvent } from "react";
import { ArrowLeft, Bot, CircleAlert, CircleCheck, Clock3, ListChecks, LoaderCircle, MessageSquareText, QrCode, Send, Unplug, Vote } from "lucide-react";
import AccountActions from "../account-actions";

type Status = { state: string; qr: string | null; phone: string | null; last_error: string | null; heartbeat_at: number; online: boolean };
type Group = { jid: string; subject: string; size: number; bot_is_admin: number };
type Command = { id: string; kind: string; status: string; attempts: number; error: string | null; created_at: number; sent_at: number | null; subject: string | null; payload: { text?: string; pollId?: string } };
type Voter = { voter_jid: string; voter_phone: string | null; name: string | null; voted_at: number };
type Poll = { id: string; name: string; subject: string | null; message_id: string | null; created_at: number; options: string[]; tally: { option: string; voters: Voter[] }[] };
type Event = Voter & { poll_name: string; selected: string[] };
type Data = { status: Status | null; groups: Group[]; outbox: Command[]; polls: Poll[]; history: Event[] };

const time = (ms: number) => new Date(ms).toLocaleString("pt-BR", { day: "2-digit", month: "2-digit", hour: "2-digit", minute: "2-digit", second: "2-digit" });
const who = (v: Voter) => v.name || (v.voter_phone ? `+${v.voter_phone}` : "Número oculto");
const phone = (p: string | null) => p ? `+${p.slice(0, 2)} (${p.slice(2, 4)}) ${p.slice(4, -4)}-${p.slice(-4)}` : "";
const stateLabel: Record<string, string> = { starting: "Iniciando", qr: "Aguardando leitura do QR code", connecting: "Conectando", open: "Conectado", closed: "Desconectado (tentando de novo)", logged_out: "Número desconectado" };
const commandLabel: Record<string, string> = { pending: "Na fila", sending: "Enviando", sent: "Enviado", failed: "Falhou" };

async function post(action: string, body: unknown) {
  const response = await fetch(`/api/staff/bot/${action}`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) });
  const result = await response.json().catch(() => ({})) as { error?: string };
  if (!response.ok) throw new Error(result.error || "Não foi possível enviar o comando.");
}

function Connection({ status, onLogout }: { status: Status | null; onLogout: () => void }) {
  if (!status) return <div className="bot-card"><div className="section-title"><span className="section-icon"><Bot size={21}/></span><div><h2>Robô não iniciado</h2><p>Inicie o processo do robô no servidor (veja OPERACAO.md). Esta página atualiza sozinha.</p></div></div></div>;
  const offline = !status.online && status.state === "open";
  return <div className="bot-card">
    <div className="section-title"><span className={`section-icon ${status.online ? "bot-ok" : "bot-warn"}`}>{status.online ? <CircleCheck size={21}/> : <CircleAlert size={21}/>}</span>
      <div><h2>{offline ? "Sem sinal do robô" : stateLabel[status.state] || status.state}</h2>
        <p>{status.phone ? `Número do robô: ${phone(status.phone)} · ` : ""}último sinal {time(status.heartbeat_at)}</p></div></div>
    {offline && <p className="notice-box">O processo do robô parou de responder. Confira se o servidor dele está ligado.</p>}
    {status.last_error && status.state !== "open" && <p className="notice-box">{status.last_error}</p>}
    {status.state === "qr" && status.qr && <div className="bot-qr">
      {/* eslint-disable-next-line @next/next/no-img-element -- data: URL generated by the worker */}
      <img src={status.qr} alt="QR code para conectar o WhatsApp do robô" width={260} height={260}/>
      <ol><li>No celular do número do robô, abra o WhatsApp.</li><li>Toque em <b>Aparelhos conectados</b> › <b>Conectar um aparelho</b>.</li><li>Aponte a câmera para este código. Ele muda a cada poucos segundos.</li></ol>
    </div>}
    {status.state === "open" && <button className="text-button bot-danger" onClick={onLogout}><Unplug size={15}/> Desconectar este número</button>}
  </div>;
}

function Commands({ groups, onSent }: { groups: Group[]; onSent: () => void }) {
  const [kind, setKind] = useState<"text" | "poll">("text"), [group, setGroup] = useState("");
  const [busy, setBusy] = useState(false), [error, setError] = useState(""), [done, setDone] = useState("");
  const groupJid = group || groups[0]?.jid || "";
  async function submit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault(); if (busy) return;
    const form = event.currentTarget, data = new FormData(form);
    setBusy(true); setError(""); setDone("");
    try {
      if (kind === "text") await post("text", { groupJid, text: data.get("text"), mentionAll: data.get("mentionAll") === "on" });
      else await post("poll", { groupJid, name: data.get("name"), options: String(data.get("options") || "").split("\n").map(o => o.trim()).filter(Boolean) });
      form.reset(); setDone("Comando na fila. O robô envia em alguns segundos."); onSent();
    } catch (e) { setError(e instanceof Error ? e.message : "Tente novamente."); } finally { setBusy(false); }
  }
  return <div className="bot-card">
    <div className="section-title"><span className="section-icon"><Send size={21}/></span><div><h2>Enviar teste</h2><p>Use um grupo de teste antes de operar no grupo de leilões.</p></div></div>
    {groups.length === 0 ? <p className="member-empty">O robô ainda não está em nenhum grupo. Adicione o número dele a um grupo de teste.</p> : <form className="auth-form bot-form" onSubmit={submit}>
      <label className="field auth-field">Grupo<select value={groupJid} onChange={e => setGroup(e.target.value)}>{groups.map(g => <option key={g.jid} value={g.jid}>{g.subject} ({g.size} pessoas){g.bot_is_admin ? " · robô é admin" : ""}</option>)}</select></label>
      <div className="bot-tabs" role="radiogroup" aria-label="Tipo de envio">
        <button type="button" role="radio" aria-checked={kind === "text"} className={kind === "text" ? "active" : ""} onClick={() => setKind("text")}><MessageSquareText size={15}/> Mensagem</button>
        <button type="button" role="radio" aria-checked={kind === "poll"} className={kind === "poll" ? "active" : ""} onClick={() => setKind("poll")}><Vote size={15}/> Enquete</button>
      </div>
      {kind === "text" ? <>
        <label className="field auth-field">Mensagem<textarea name="text" required maxLength={4000} rows={4}/></label>
        <label className="member-check"><input type="checkbox" name="mentionAll"/><span>Marcar todos do grupo</span></label>
      </> : <>
        <label className="field auth-field">Título<input name="name" required maxLength={255} placeholder="Charizard VMAX — lance"/></label>
        <label className="field auth-field">Opções (uma por linha, até 12)<textarea name="options" required rows={5} placeholder={"R$ 10\nR$ 12\nR$ 14"}/></label>
      </>}
      {error && <p className="error-box" role="alert">{error}</p>}
      {done && <p className="auth-success" role="status"><CircleCheck size={16}/> {done}</p>}
      <button className="primary-button" disabled={busy || !groupJid}>{busy ? <LoaderCircle className="spin" size={17}/> : <Send size={17}/>} Colocar na fila</button>
    </form>}
  </div>;
}

export default function BotPanel() {
  const [data, setData] = useState<Data | null>(null), [error, setError] = useState("");
  const load = useCallback(async () => {
    const response = await fetch("/api/staff/bot", { cache: "no-store" });
    if (response.status === 401) { setError("Sua sessão terminou. Entre novamente."); return; }
    if (!response.ok) throw new Error();
    setData(await response.json() as Data); setError("");
  }, []);
  useEffect(() => {
    let live = true;
    const tick = () => load().catch(() => { if (live) setError("Não foi possível atualizar. Tentando de novo…"); });
    const first = setTimeout(tick, 0), timer = setInterval(tick, 4000);
    return () => { live = false; clearTimeout(first); clearInterval(timer); };
  }, [load]);
  async function logout() {
    if (!window.confirm("Desconectar o número do robô? Será preciso ler um novo QR code para conectar de novo.")) return;
    try { await post("logout", {}); } catch (e) { setError(e instanceof Error ? e.message : "Tente novamente."); }
  }
  return <><div className="color-ribbon"/><main className="staff-shell">
    <div className="staff-navigation"><Link href="/equipe" className="back-button"><ArrowLeft size={17}/> Voltar aos pedidos</Link><AccountActions/></div>
    <div className="eyebrow"><span/> ÁREA DA EQUIPE</div>
    <h1>Robô do <span>WhatsApp</span></h1>
    {error && <p className="error-box" role="alert">{error}</p>}
    {!data ? <p className="member-loading"><LoaderCircle className="spin" size={18}/> Carregando…</p> : <div className="bot-grid">
      <Connection status={data.status} onLogout={logout}/>
      <Commands groups={data.groups} onSent={() => { load().catch(() => {}); }}/>
      <section className="bot-card bot-wide" aria-labelledby="polls-title">
        <div className="section-title"><span className="section-icon"><ListChecks size={21}/></span><div><h2 id="polls-title">Enquetes recentes</h2><p>Voto atual de cada pessoa. Atualiza a cada 4 segundos.</p></div></div>
        {data.polls.length === 0 ? <p className="member-empty">Nenhuma enquete enviada ainda.</p> : data.polls.map(p => <article key={p.id} className="bot-poll">
          <header><strong>{p.name}</strong><span>{p.subject || "grupo"} · {p.message_id ? `enviada ${time(p.created_at)}` : "na fila"}</span></header>
          <ul>{p.tally.map(t => <li key={t.option}><span className="bot-option">{t.option}</span><b>{t.voters.length}</b><span className="bot-voters">{t.voters.map(who).join(", ")}</span></li>)}</ul>
        </article>)}
      </section>
      <section className="bot-card" aria-labelledby="history-title">
        <div className="section-title"><span className="section-icon"><Clock3 size={21}/></span><div><h2 id="history-title">Histórico de votos</h2><p>Toda mudança fica registrada, inclusive votos removidos.</p></div></div>
        {data.history.length === 0 ? <p className="member-empty">Nenhum voto recebido ainda.</p> : <ol className="bot-history">{data.history.map((h, i) => <li key={i} className={h.selected.length ? "" : "removed"}>
          <time>{time(h.voted_at)}</time><span><b>{who(h)}</b> {h.selected.length ? <>votou em <b>{h.selected.join(", ")}</b></> : <b>removeu o voto</b>} · {h.poll_name}</span>
        </li>)}</ol>}
      </section>
      <section className="bot-card" aria-labelledby="queue-title">
        <div className="section-title"><span className="section-icon"><QrCode size={21}/></span><div><h2 id="queue-title">Fila de envio</h2><p>Últimos comandos enviados ao robô.</p></div></div>
        {data.outbox.length === 0 ? <p className="member-empty">Nada na fila.</p> : <ol className="bot-history">{data.outbox.map(c => <li key={c.id} className={c.status === "failed" ? "removed" : ""}>
          <time>{time(c.sent_at || c.created_at)}</time>
          <span><b>{commandLabel[c.status] || c.status}</b> · {c.kind === "poll" ? "enquete" : c.kind === "logout" ? "desconectar" : c.kind === "image" ? "imagem" : "mensagem"}{c.subject ? ` em ${c.subject}` : ""}{c.payload.text ? ` — “${c.payload.text.slice(0, 60)}”` : ""}{c.error ? ` · ${c.error}` : ""}</span>
        </li>)}</ol>}
      </section>
    </div>}
  </main></>;
}
